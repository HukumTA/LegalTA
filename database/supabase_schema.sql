-- ==========================================================
-- LEGALTA Database Schema for Supabase (PostgreSQL)
-- Based on ERD.Md & PRD.Md Specifications
-- Platform: Supabase PostgreSQL 15+
-- ==========================================================

-- Enable pgcrypto extension for UUID generation if needed
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ==========================================================
-- 1. USERS TABLE
-- ==========================================================
CREATE TABLE IF NOT EXISTS public.users (
    id TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT,
    phone_number TEXT,
    role TEXT NOT NULL DEFAULT 'CLIENT' CHECK (role IN ('CLIENT', 'ADMIN', 'PLA')),
    avatar_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==========================================================
-- 2. SERVICE CATEGORIES TABLE
-- ==========================================================
CREATE TABLE IF NOT EXISTS public.service_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT UNIQUE NOT NULL,
    description TEXT
);

-- ==========================================================
-- 3. SERVICES TABLE
-- ==========================================================
CREATE TABLE IF NOT EXISTS public.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES public.service_categories(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    slug TEXT UNIQUE NOT NULL,
    description TEXT,
    base_price NUMERIC(15, 2) NOT NULL DEFAULT 0,
    estimated_days INTEGER DEFAULT 3
);

-- ==========================================================
-- 4. ORDERS TABLE (PRD 3.C)
-- ==========================================================
CREATE TABLE IF NOT EXISTS public.orders (
    id TEXT PRIMARY KEY, -- e.g. 'LEG-2025-0891'
    user_id TEXT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    service_id BIGINT NOT NULL REFERENCES public.services(id) ON DELETE RESTRICT,
    pla_id TEXT REFERENCES public.users(id) ON DELETE SET NULL, -- Assigned Personal Legal Assistant
    title TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ON_PROGRESS', 'COMPLETED', 'CANCELLED')),
    total_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    voucher_code TEXT,
    kemenkumham_id TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==========================================================
-- 5. ORDER TRACKING TABLE (PRD 3.C Live Milestone Tracking)
-- ==========================================================
CREATE TABLE IF NOT EXISTS public.order_tracking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id TEXT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    step_number INTEGER NOT NULL,
    step_name TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('DONE', 'JALAN', 'PENDING')),
    description TEXT,
    completed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_order_step UNIQUE (order_id, step_number)
);

-- ==========================================================
-- 6. DOCUMENTS TABLE (PRD 3.C Enkripsi & Arsip Dokumen Legal)
-- ==========================================================
CREATE TABLE IF NOT EXISTS public.documents (
    id TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
    order_id TEXT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    uploaded_by TEXT REFERENCES public.users(id) ON DELETE SET NULL,
    file_name TEXT NOT NULL,
    file_url TEXT NOT NULL,
    file_size TEXT,
    doc_type TEXT NOT NULL DEFAULT 'OTHER' CHECK (doc_type IN ('KTP', 'NPWP', 'AKTA', 'NIB', 'SK_MENKUMHAM', 'VOUCHER', 'OTHER')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==========================================================
-- 7. CONSULTATIONS TABLE (Public Leads / Booking Jadwal)
-- ==========================================================
CREATE TABLE IF NOT EXISTS public.consultations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_name TEXT NOT NULL,
    phone_number TEXT NOT NULL,
    email TEXT NOT NULL,
    city TEXT,
    service_slug TEXT,
    consult_method TEXT DEFAULT 'whatsapp' CHECK (consult_method IN ('whatsapp', 'gmeet', 'office')),
    notes TEXT,
    status TEXT DEFAULT 'NEW' CHECK (status IN ('NEW', 'CONTACTED', 'RESOLVED')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==========================================================
-- 8. KBLI 2020 REFERENCE TABLE (Public Tool Engine)
-- ==========================================================
CREATE TABLE IF NOT EXISTS public.kbli_items (
    code TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    sector_name TEXT NOT NULL,
    description TEXT NOT NULL,
    risk_level TEXT NOT NULL CHECK (risk_level IN ('R', 'MR', 'MT', 'T')),
    permits_required TEXT NOT NULL,
    dpi_rules TEXT NOT NULL
);

-- ==========================================================
-- 9. REGISTERED PT REFERENCE TABLE (Cek Nama PT Engine)
-- ==========================================================
CREATE TABLE IF NOT EXISTS public.registered_pts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    status TEXT DEFAULT 'ACTIVE',
    ahu_number TEXT,
    registration_date DATE
);

-- ==========================================================
-- 10. REGISTERED TRADEMARKS REFERENCE TABLE (Cek Merek PDKI)
-- ==========================================================
CREATE TABLE IF NOT EXISTS public.registered_trademarks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name TEXT NOT NULL,
    nice_class INTEGER NOT NULL,
    application_number TEXT UNIQUE NOT NULL,
    owner_name TEXT NOT NULL,
    status TEXT NOT NULL,
    phonetic_key TEXT
);

-- ==========================================================
-- INDEXES FOR PERFORMANCE
-- ==========================================================
CREATE INDEX IF NOT EXISTS idx_services_category_id ON public.services(category_id);
CREATE INDEX IF NOT EXISTS idx_orders_user_id ON public.orders(user_id);
CREATE INDEX IF NOT EXISTS idx_orders_service_id ON public.orders(service_id);
CREATE INDEX IF NOT EXISTS idx_order_tracking_order_id ON public.order_tracking(order_id);
CREATE INDEX IF NOT EXISTS idx_documents_order_id ON public.documents(order_id);
CREATE INDEX IF NOT EXISTS idx_kbli_code ON public.kbli_items(code);
CREATE INDEX IF NOT EXISTS idx_registered_pts_name ON public.registered_pts(name);
CREATE INDEX IF NOT EXISTS idx_registered_trademarks_brand ON public.registered_trademarks(brand_name);

