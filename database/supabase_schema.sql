ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_tracking ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.consultations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kbli_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.registered_pts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.registered_trademarks ENABLE ROW LEVEL SECURITY;

-- Allow public read on catalog & reference tables
CREATE POLICY "Public read service_categories" ON public.service_categories FOR SELECT USING (true);
CREATE POLICY "Public read services" ON public.services FOR SELECT USING (true);
CREATE POLICY "Public read orders" ON public.orders FOR SELECT USING (true);
CREATE POLICY "Public read order_tracking" ON public.order_tracking FOR SELECT USING (true);
CREATE POLICY "Public read documents" ON public.documents FOR SELECT USING (true);
CREATE POLICY "Public read kbli_items" ON public.kbli_items FOR SELECT USING (true);
CREATE POLICY "Public read registered_pts" ON public.registered_pts FOR SELECT USING (true);
CREATE POLICY "Public read registered_trademarks" ON public.registered_trademarks FOR SELECT USING (true);
CREATE POLICY "Public read users" ON public.users FOR SELECT USING (true);

-- Allow public / client insert on consultations and documents
CREATE POLICY "Public insert consultations" ON public.consultations FOR INSERT WITH CHECK (true);
CREATE POLICY "Public insert documents" ON public.documents FOR INSERT WITH CHECK (true);
CREATE POLICY "Public read consultations" ON public.consultations FOR SELECT USING (true);

